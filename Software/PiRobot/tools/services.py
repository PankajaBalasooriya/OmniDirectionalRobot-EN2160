#!/usr/bin/env python3
"""Generate/install system boot services. Default is dry-run; never arms motors."""
import argparse
from datetime import datetime, timezone
import os
from pathlib import Path
import pwd
import shutil
import subprocess
import sys

from common import BACKEND_PYTHON, ROOT, ROS_SETUP, WORKSPACE, load_config

UNITS = ("omni-lidar.service", "omni-ui.service")


def quote(value, *, executable=False):
    value = str(value)
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise ValueError("Control characters are not allowed in systemd values")
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if executable:
        value = value.replace("$", "$$")
    return '"' + value + '"'


def render_units(user, config, *, project=ROOT):
    if not user or not all(char.isalnum() or char in "_-" for char in user):
        raise ValueError("Use a simple local Linux username")
    if user == "root":
        raise ValueError("Services must run as a non-root operator")
    project = Path(project).resolve()
    if str(project) != str(project).strip() or "\\" in str(project):
        raise ValueError("Checkout path cannot contain backslashes or outer whitespace")
    config = Path(config).resolve()
    command = " ".join(quote(arg, executable=True) for arg in
                       ("/usr/bin/python3", project / "tools/run.py"))
    common = f"""[Unit]
Wants=network-online.target
After=network-online.target
StartLimitIntervalSec=0

[Service]
Type=simple
User={user}
SupplementaryGroups=dialout
WorkingDirectory={str(project).replace("%", "%%")}
Environment=PYTHONUNBUFFERED=1
Restart=on-failure
RestartSec=5
KillSignal=SIGINT
KillMode=control-group
TimeoutStopSec=15
NoNewPrivileges=true
ProtectSystem=full
ProtectHome=read-only

[Install]
WantedBy=multi-user.target
"""
    def unit(component):
        extra = ""
        if component == "lidar":
            extra = ("StateDirectory=omni-lidar\n"
                     "Environment=ROS_HOME=/var/lib/omni-lidar\n"
                     "Environment=ROS_LOG_DIR=/var/lib/omni-lidar/log\n")
        definition = common
        if component == "lidar":
            # ROS launch may exit successfully after its driver exits; still retry sensing.
            definition = definition.replace("Restart=on-failure", "Restart=always")
        start = f"ExecStart={command} {component} --config {quote(config, executable=True)}\n"
        # No --uart or --enable-hardware-motion is accepted or generated.
        return (f"# Generated by PiRobot/tools/services.py; motor motion is never armed.\n"
                + definition.replace("[Unit]\n", f"[Unit]\nDescription=Omni robot {component} (safe boot)\n", 1)
                .replace("Type=simple\n", "Type=simple\n" + extra + start, 1))
    return {UNITS[0]: unit("lidar"), UNITS[1]: unit("backend")}


def validate_configuration(path):
    config = load_config(path)
    sys.path.insert(0, str(WORKSPACE / "src/omni_bringup"))
    from omni_bringup.config_validation import load_mount, validate_serial_port
    validate_serial_port(config["lidar_port"])
    load_mount(config["mount_config"])
    return config


def write_units(units, directory):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    for name in units:
        if (directory / name).is_symlink():
            raise ValueError(f"Refusing symlink unit file: {directory / name}")
    for name, content in units.items():
        destination = directory / name
        if destination.is_symlink():
            raise ValueError(f"Refusing symlink unit file: {destination}")
        if destination.exists() and destination.read_text() == content:
            continue
        if destination.exists():
            backup = destination.with_name(name + ".backup-" + stamp)
            shutil.copy2(destination, backup)
            print(f"Backup: {backup}")
        destination.write_text(content)
        destination.chmod(0o644)
        print(f"Wrote {destination}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--user", required=True, help="Non-root account owning the prepared checkout")
    parser.add_argument("--config", type=Path, default=ROOT / "config/robot.json")
    parser.add_argument("--output-dir", type=Path, help="Generate files here only; never installs/enables")
    parser.add_argument("--apply", action="store_true", help="Install system units; requires sudo")
    parser.add_argument("--enable", action="store_true", help="Enable and start installed units now (requires --apply)")
    args = parser.parse_args()
    if args.output_dir and (args.apply or args.enable):
        parser.error("--output-dir cannot be combined with --apply/--enable")
    if args.enable and not args.apply:
        parser.error("--enable requires --apply")
    operator = pwd.getpwnam(args.user)
    if operator.pw_uid == 0:
        raise ValueError("Do not run services as root")
    config = args.config.expanduser().resolve()
    validate_configuration(config)
    # No serial access, mount approval changes, or network queries during installation.
    for path in (ROOT / "tools/run.py", BACKEND_PYTHON, ROS_SETUP,
                 WORKSPACE / "install/setup.bash"):
        if not path.is_file():
            raise ValueError(f"Missing prepared file: {path}; run prepare.py --apply first")
    units = render_units(args.user, config)
    if args.output_dir:
        write_units(units, args.output_dir)
        return
    if not args.apply:
        for name, text in units.items():
            print(f"--- {name} ---\n{text}")
        print("Dry run only. Use sudo with --apply to install; add --enable to start at boot and now.")
        return
    if os.geteuid() != 0:
        raise ValueError("Installation requires sudo; services themselves run as the specified user")
    # Check existing jobs first; do not rewrite configuration under a running robot process.
    for name in UNITS:
        active = subprocess.run(["systemctl", "is-active", name], capture_output=True, text=True)
        if active.stdout.strip() in {"active", "activating", "deactivating", "reloading"}:
            raise ValueError(f"Stop {name} explicitly before updating its unit")
    write_units(units, "/etc/systemd/system")
    subprocess.run(["systemctl", "daemon-reload"], check=True)
    if args.enable:
        subprocess.run(["systemctl", "enable", "--now", *UNITS], check=True)
    print("Installed safe boot services. UI is simulation; motor UART is not opened.")
    print("Check systemctl status and journalctl; installed/enabled is not proof of healthy scans.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError) as exc:
        sys.exit(str(exc))
